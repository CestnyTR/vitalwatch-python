"""Kurulum teşhisi — ``vitalwatch-status``.

Paketin en pahalı arıza biçimi için var: **sessiz çalışmama.** Yapılandırma
eksikken ya da secret yanlışken hiçbir şey patlamaz, hiçbir log düşmez — hub
geçersiz isteğe de 204 döner (saldırgana geri bildirim verilmez). Sonuç,
kimsenin fark etmediği bir izleme kurulumu.

Komut tek başına "çalışıyor" diyemez: hub geçerli ile geçersiz imzayı dışarıya
aynı yanıtla karşılar. Yaptığı iş, yerelde yanlış olan ne varsa göstermek ve
doğrulamanın hub panelinden yapılacağını söylemek.
"""

import json
import os
import re
import sys
import urllib.request

from . import __version__, dependencies, init, report, reporter
from .env import env as read_env
from .release import detect as detect_release
from .reporter import ENVIRONMENTS, normalize_env

#: Yayımlanmış en yeni sürüm PyPI'dan okunur (``info.version``).
PYPI_URL = "https://pypi.org/pypi/vitalwatch/json"
UPDATE_TIMEOUT = 2.0

#: Kararlı sürüm: ``1.2.3`` ya da ``v1.2.3``; ön sürüm (``-rc1``) sayılmaz.
_STABLE = re.compile(r"[vV]?(\d+)\.(\d+)\.(\d+)")

#: Panelden gelen secret'in uzunluğu. En sık kurulum hatası eksik kopyalamadır
#: ve sonucu sessizce hiçbir şey göndermemektir.
SECRET_LENGTH = 64


def _line(label, value):
    print(f"  {label:<18} {value}")


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv

    # Süreç ortamı VE .env birlikte okunur. Yalnızca os.environ'a bakan bir
    # teşhis, .env doğru doldurulmuş bir kurulumda "NOT SET" der — teşhis
    # aracının yanlış teşhis koyması, hiç teşhis koymamaktan kötüdür.
    values = read_env()
    secret = values.get("VITALWATCH_SECRET", "")
    url = values.get("VITALWATCH_URL", "")

    print("")
    _line("SDK version", __version__)
    _update_lines(values)
    _line("Enabled", "NO (VITALWATCH_ENABLED=false)" if values.get("VITALWATCH_ENABLED") == "false" else "yes")
    _line("Hub URL", url or "NOT SET")
    _line("Project key", values.get("VITALWATCH_KEY") or "NOT SET")
    _line("Secret length", f"{len(secret)} characters" if secret else "NOT SET")
    env_raw = values.get("VITALWATCH_ENV") or os.environ.get("APP_ENV") or "production"
    env_name = normalize_env(env_raw)
    _line("Environment", env_name if env_name == env_raw else f"{env_name} ({env_raw})")
    _line("Python", sys.version.split()[0])
    release, source = detect_release(values=values)
    _line("Release tag", f"{release or 'not set'} (source: {source or 'none'})")
    _line("Dependencies", _dependencies_label(values))
    print("")

    problems = []

    if env_name not in ENVIRONMENTS:
        problems.append(
            f'Environment "{env_raw}" is not accepted by the hub — events and heartbeats are '
            "silently rejected. Set VITALWATCH_ENV to production, staging or local."
        )

    if values.get("VITALWATCH_ENABLED") == "false":
        problems.append("VITALWATCH_ENABLED=false — no data is sent.")

    missing = [key for key in ("VITALWATCH_URL", "VITALWATCH_KEY", "VITALWATCH_SECRET") if not values.get(key)]

    if missing:
        problems.append(f"{', '.join(missing)} not set.")

    if secret and len(secret) != SECRET_LENGTH:
        problems.append(
            f"VITALWATCH_SECRET must be {SECRET_LENGTH} characters, got {len(secret)}. "
            "It may have been copied incompletely."
        )

    if url.startswith("http://"):
        problems.append("VITALWATCH_URL starts with http:// — the secret signature travels over an unencrypted connection.")

    if problems:
        for problem in problems:
            print(f"  ✗ {problem}", file=sys.stderr)
        print("")

        return 1

    print("  ✓ Configuration OK.")

    init()

    if "--test" in argv:
        # Gerçek bir hata raporlanır: hem taşıma hem temizlik sınanmış olur.
        # Sonuç okunuyor, "gönderdim" varsayılmıyor — koşulsuz başarı yazan
        # bir teşhis, ağ koptuğunda da "✓" der ve kuran kişi kurulumu çalışır
        # sanır.
        result = report(RuntimeError("Test event generated by vitalwatch-status --test"), block=True)

        if not _report_result("Test event", result):
            return 1

    # --vitalwatch: bağlantıyı panele hata düşürmeden sınar. --test tek kurulumu
    # doğrularken doğru; onlarca kurulumu gezen bir güncelleme döngüsünde ise
    # panele onlarca sahte hata bırakır — izleme aracının kendi gürültüsünü
    # üretmesi.
    if "--vitalwatch" in argv:
        if not _report_result("Heartbeat", reporter().heartbeat(block=True)):
            return 1

    # --deps: bağımlılık listesini hemen gönderir (normalde açılıştan ~60 sn
    # sonra canlılık thread'i gönderir). --test ve --vitalwatch göndermez.
    if "--deps" in argv:
        if not _report_result("Dependencies", reporter().send_dependencies()):
            return 1

    print("")
    print("  Only the hub panel can confirm that data arrives:")
    print('  the project row should show the connection status "Connected".')
    print("  The hub returns 204 for an invalid signature too, so this command cannot tell.")
    print("")

    return 0


def _dependencies_label(values):
    """``installed distributions · 87 packages`` ya da ``disabled``. Ağa çıkmaz."""
    if values.get("VITALWATCH_ENABLED") == "false" or not dependencies.enabled_in(values):
        return "disabled"

    try:
        count = len(dependencies.collect())
    except Exception:  # noqa: BLE001
        return "not readable"

    return f"installed distributions · {count} packages"


def _update_lines(values):
    """PyPI'daki en yeni kararlı sürüm; yeniyse uyarı.

    Uyarıdır, hata değil: çıkış kodu değişmez — güncelleme döngüsündeki
    betikler eski sürümü "bozuk kurulum" saymasın. Ağ yoksa ya da hız
    sınırına takıldıysa "could not check" yazılır. ``VITALWATCH_STATUS_OFFLINE=1``
    denetimi tamamen atlar.
    """
    try:
        flag = os.environ.get("VITALWATCH_STATUS_OFFLINE") or values.get("VITALWATCH_STATUS_OFFLINE")

        if str(flag or "").strip().lower() in ("1", "true", "yes", "on", "evet"):
            return

        latest = latest_version()

        if latest is None:
            _line("Latest version", "could not check")
            return

        _line("Latest version", latest)

        installed = _stable(__version__)

        if installed is None or _stable(latest) > installed:
            print("  ! Update available: pip install -U vitalwatch")
    except Exception:  # noqa: BLE001
        _line("Latest version", "could not check")


def latest_version(timeout=UPDATE_TIMEOUT):
    """PyPI'daki güncel kararlı sürüm (``"0.2.0"``) ya da ``None``. Hiç fırlatmaz.

    ``info.version`` PyPI'ın "en yeni" saydığı sürümdür; ön sürüm (``-rc1``,
    ``0.3.0rc1``) kararlı sayılmaz ve uyarı üretmez.
    """
    try:
        request = urllib.request.Request(
            PYPI_URL,
            headers={
                "User-Agent": f"vitalwatch/{__version__} (vitalwatch-status)",
                "Accept": "application/json",
            },
        )

        with urllib.request.urlopen(request, timeout=timeout) as response:  # noqa: S310
            data = json.loads(response.read(4 * 1024 * 1024).decode("utf-8"))

        version = data.get("info", {}).get("version") if isinstance(data, dict) else None
        parsed = _stable(version)

        if parsed is None:
            return None

        return ".".join(str(part) for part in parsed)
    except Exception:  # noqa: BLE001
        return None


def _stable(name):
    if not isinstance(name, str):
        return None

    match = _STABLE.fullmatch(name.strip())

    return tuple(int(part) for part in match.groups()) if match else None


def _report_result(label, result):
    if result and result.get("sent"):
        print(f"  ✓ {label} sent (HTTP {result.get('status')}).")

        return True

    reason = (result or {}).get("error") or f"HTTP {(result or {}).get('status')}"
    print(f"  ✗ {label} NOT SENT: {reason}", file=sys.stderr)
    print("")

    return False


if __name__ == "__main__":
    sys.exit(main())
