"""``vitalwatch-agent run | check [--test] | status | systemd``."""

import argparse
import json
import sys
import threading

from ..client import HubClient
from ..reporter import ENVIRONMENTS, SDK_VERSION
from . import config as config_module
from .runner import DISABLED, FOUND, NOT_FOUND, Agent, source_report
from .sender import identity
from .status import STATUS_INTERVAL, collector_for

#: Panelden gelen secret'in uzunluğu (``vitalwatch-status`` ile aynı kontrol).
SECRET_LENGTH = 64

TEST_MESSAGE = "Test event generated by vitalwatch-agent check --test"


HTTP_WARNING = "Hub URL starts with http:// — the secret signature travels over an unencrypted connection."


def hub_problems(config):
    """Hub yapılandırmasındaki sorunlar (``vitalwatch-status`` ile aynı kurallar)."""
    problems = list(config.errors)

    missing = [name for name, value in (("url", config.url), ("key", config.key), ("secret", config.secret)) if not value]

    if missing:
        problems.append(
            f"[hub] {', '.join(missing)} not set (agent.ini or VITALWATCH_URL/KEY/SECRET)."
        )

    if config.secret and len(config.secret) != SECRET_LENGTH:
        problems.append(
            f"secret must be {SECRET_LENGTH} characters, got {len(config.secret)}. It may have been copied incompletely."
        )

    if config.url and config.url.startswith("http://"):
        problems.append(HTTP_WARNING)

    if config.env not in ENVIRONMENTS:
        problems.append(f'Environment "{config.env_raw}" is not accepted by the hub; use production, staging or local.')

    return problems


def _line(label, value):
    print(f"  {label:<18} {value}")


def command_check(config, send_test=False):
    print("")
    _line("Agent version", SDK_VERSION)
    _line("Python", sys.version.split()[0])
    _line("Configuration", f"{config.path}" + ("" if config.file_found else " (missing — environment variables only)"))
    _line("Hub URL", config.url or "NOT SET")
    _line("Project key", config.key or "NOT SET")
    _line("Secret length", f"{len(config.secret)} characters" if config.secret else "NOT SET")
    _line("Environment", config.env)
    _line("Enabled", "yes" if config.enabled else "NO (VITALWATCH_ENABLED=false)")
    _line("Ignored hosts", ", ".join(config.ignore_rules().hosts) or "—")
    print("")
    print("  Sources:")

    rows = source_report(config)
    problems = hub_problems(config)

    for name, status, detail in rows:
        mark = "✓" if status == FOUND else ("-" if status in (DISABLED, NOT_FOUND) else "✗")
        print(f"   {mark} {name:<16} {status:<12} {detail}".rstrip())

        if status != FOUND and config.source_mode(name) == "on":
            problems.append(f"{name} source is 'on' but {status}.")

    method = collector_for(config).update_method()
    _line("Status snapshot", f"every {int(STATUS_INTERVAL // 60)} min (updates: {method or 'not available'})")
    print("")

    if not config.enabled:
        problems.append("VITALWATCH_ENABLED=false — no data is sent.")

    if problems:
        for problem in problems:
            print(f"  ✗ {problem}", file=sys.stderr)
        print("")

        return 1

    print("  ✓ Configuration OK.")

    if send_test:
        client = HubClient(url=config.url, key=config.key, secret=config.secret, timeout=config.timeout)
        body = dict(identity(config.env), events=[{"kind": "log_error", "msg": TEST_MESSAGE, "file": "vitalwatch-agent"}])
        result = client.send(body)

        if result.get("sent"):
            print(f"  ✓ Test event sent (HTTP {result.get('status')}).")
        else:
            reason = result.get("error") or f"HTTP {result.get('status')}"
            print(f"  ✗ Test event NOT SENT: {reason}", file=sys.stderr)
            print("")

            return 1

    print("")
    print("  Only the hub panel can confirm that data arrives: the hub returns 204")
    print("  for an invalid signature too. The test event should appear as 'log_error'.")
    print("")

    return 0


def command_status(config):
    """Tek bir durum özeti toplar ve JSON olarak yazar; gönderilmez."""
    snapshot = collector_for(config).collect()
    print(json.dumps(snapshot, indent=2, ensure_ascii=False))

    return 0


def systemd_unit(python=None, config_path=None):
    """Hardened systemd unit file using the interpreter of the running installation."""
    python = python or sys.executable
    config_arg = f" --config {config_path}" if config_path and config_path != config_module.DEFAULT_PATH else ""

    # Sanal ortam /home ya da /root altındaysa ProtectHome=yes, /tmp altındaysa
    # PrivateTmp=yes yorumlayıcıyı görünmez yapar ve servis hiç açılmaz.
    notes = []
    protect_home = "yes"
    private_tmp = "yes"

    if python.startswith(("/home/", "/root/", "/run/user/")):
        protect_home = "read-only"
        notes.append("# Interpreter is under a home directory: ProtectHome=read-only. If you move\n# the installation under /opt, set ProtectHome=yes.\n")

    if python.startswith(("/tmp/", "/var/tmp/")):
        private_tmp = "no"
        notes.append("# Interpreter is under /tmp: PrivateTmp=no. A venv under /opt is recommended for a permanent install.\n")

    note = "".join(notes)

    return f"""# /etc/systemd/system/vitalwatch-agent.service
# vitalwatch-agent systemd > /etc/systemd/system/vitalwatch-agent.service
# systemctl daemon-reload && systemctl enable --now vitalwatch-agent
[Unit]
Description=VitalWatch server agent
Documentation=https://github.com/CestnyTR/vitalwatch-python
After=network-online.target docker.service
Wants=network-online.target

[Service]
Type=simple
# root: Plesk vhost logs and the Docker socket cannot be read otherwise.
User=root
ExecStart={python} -m vitalwatch.agent run{config_arg}
Restart=always
RestartSec=10
Environment=PYTHONUNBUFFERED=1
Nice=10
StateDirectory=vitalwatch-agent
StateDirectoryMode=0700
ProtectSystem=strict
ReadWritePaths=/var/lib/vitalwatch-agent
{note}ProtectHome={protect_home}
PrivateTmp={private_tmp}
NoNewPrivileges=yes
ProtectKernelModules=yes
ProtectKernelTunables=yes
ProtectControlGroups=yes
RestrictSUIDSGID=yes
LockPersonality=yes

[Install]
WantedBy=multi-user.target
"""


def command_run(config):
    for error in config.errors:
        print(f"vitalwatch-agent: {error}", file=sys.stderr)

    problems = [problem for problem in hub_problems(config) if problem not in config.errors]

    # http:// teşhiste hata, serviste uyarı: hub aynı makinedeyse
    # http://127.0.0.1 meşru bir kurulum.
    if HTTP_WARNING in problems:
        problems.remove(HTTP_WARNING)
        print(f"vitalwatch-agent: {HTTP_WARNING}", file=sys.stderr)

    if problems:
        for problem in problems:
            print(f"vitalwatch-agent: {problem}", file=sys.stderr)

        return 1

    if not config.enabled:
        # Servis olarak çalışırken çıkmak systemd'nin Restart=always ile
        # yeniden başlatma döngüsüne girmesi olurdu: boşta beklenir.
        print("vitalwatch-agent: VITALWATCH_ENABLED=false — no data is sent, idling.", file=sys.stderr)
        import signal

        stop = threading.Event()
        signal.signal(signal.SIGTERM, lambda *_: stop.set())
        signal.signal(signal.SIGINT, lambda *_: stop.set())

        while not stop.wait(3600):
            pass

        return 0

    print(f"vitalwatch-agent {SDK_VERSION}: sending to {config.url} (env={config.env}).", file=sys.stderr)
    agent = Agent(config)
    agent.run()

    return 0


def build_parser():
    parser = argparse.ArgumentParser(prog="vitalwatch-agent", description="VitalWatch server agent")
    parser.add_argument("--config", help=f"configuration file (default {config_module.DEFAULT_PATH})")
    commands = parser.add_subparsers(dest="command")
    commands.add_parser("run", help="run as a service")
    check = commands.add_parser("check", help="check sources and configuration")
    check.add_argument("--test", action="store_true", help="send a test event to the hub")
    commands.add_parser("status", help="collect one server status snapshot and print it as JSON (not sent)")
    commands.add_parser("systemd", help="print the systemd unit file")

    # Alt komuttan sonra da --config yazılabilsin: "vitalwatch-agent run --config x".
    for sub in commands.choices.values():
        sub.add_argument("--config", dest="sub_config", help=argparse.SUPPRESS)

    return parser


def main(argv=None):
    parser = build_parser()
    args = parser.parse_args(sys.argv[1:] if argv is None else argv)
    config_path = getattr(args, "sub_config", None) or args.config

    if args.command == "systemd":
        print(systemd_unit(config_path=config_module.resolve_path(config_path)), end="")
        return 0

    if args.command not in ("run", "check", "status"):
        parser.print_help()
        return 2

    config = config_module.load(config_path)

    if args.command == "status":
        return command_status(config)

    if args.command == "check":
        return command_check(config, send_test=args.test)

    return command_run(config)


__all__ = ["main", "systemd_unit", "hub_problems", "command_check", "command_status", "NOT_FOUND"]
